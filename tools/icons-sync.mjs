#!/usr/bin/env node
// SPDX-License-Identifier: AGPL-3.0-or-later
// Copies icons from an icon service into a folder on your own server, and keeps them fresh.
// No dependencies. Needs Node 18+.
//
//   node icons-sync.mjs --out public/icons                      all icons
//   node icons-sync.mjs --out public/icons --sets ui,social     only some sets
//   node icons-sync.mjs --out public/icons --names home,user    only the icons you use
//   node icons-sync.mjs --out public/icons --css                also write zi.css next to them
//   node icons-sync.mjs --out public/icons --every 24h          keep running, refresh on a timer
//   options: --from <url>  --quiet  --prune (default) / --no-prune
import { mkdir, readFile, writeFile, rm, rename } from "node:fs/promises";
import { join, dirname } from "node:path";

const DEFAULT_ORIGIN = "__DEFAULT_ORIGIN__";
const args = process.argv.slice(2);
const opt = (n, d) => { const i = args.indexOf(`--${n}`); return i === -1 ? d : args[i + 1] && !args[i + 1].startsWith("--") ? args[i + 1] : true; };
const flag = (n) => args.includes(`--${n}`);

if (flag("help") || flag("h")) {
  console.log("Usage: node icons-sync.mjs --out <dir> [--from <url>] [--sets ui,social] [--names a,b,c] [--css] [--every 24h] [--quiet] [--no-prune]");
  process.exit(0);
}

const origin = String(opt("from", DEFAULT_ORIGIN)).replace(/\/+$/, "");
const out = opt("out", null);
const sets = opt("sets", "") ? String(opt("sets")).split(",").map((s) => s.trim()).filter(Boolean) : null;
const names = opt("names", "") ? new Set(String(opt("names")).split(",").map((s) => s.trim()).filter(Boolean)) : null;
const quiet = flag("quiet");
const prune = !flag("no-prune");
const say = (m) => { if (!quiet) console.log(m); };

if (!out || out === true) { console.error("Missing --out <folder>. Try --help."); process.exit(2); }
if (!/^https?:\/\//.test(origin)) { console.error("Missing --from <url>: the address of the icon service, e.g. --from https://icons.example.com"); process.exit(2); }

function interval(v) {
  if (!v || v === true) return 0;
  const m = /^(\d+)\s*(s|m|h|d)?$/.exec(String(v));
  if (!m) { console.error("--every expects a value like 30m, 6h or 1d"); process.exit(2); }
  return +m[1] * { s: 1, m: 60, h: 3600, d: 86400 }[m[2] || "s"] * 1000;
}

async function get(path, as = "text") {
  const res = await fetch(origin + path, { signal: AbortSignal.timeout(20000), headers: { "user-agent": "icons-sync" } });
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return as === "json" ? res.json() : res.text();
}

async function once() {
  const manifest = await get("/api/manifest", "json");
  const wanted = manifest.icons.filter((i) => (!sets || sets.includes(i.set)) && (!names || names.has(i.name)));
  if (!wanted.length) throw new Error("No icons matched --sets/--names");
  await mkdir(out, { recursive: true });
  const stateFile = join(out, ".icons-sync.json");
  let local = {};
  try { local = JSON.parse(await readFile(stateFile, "utf8")); } catch { /* first run */ }
  const next = {};
  const todo = [];
  for (const i of wanted) {
    const k = `${i.set}/${i.name}`;
    next[k] = i.hash;
    if (local[k] !== i.hash) todo.push(i);
  }
  let n = 0, idx = 0;
  await Promise.all(Array.from({ length: 6 }, async () => {
    while (idx < todo.length) {
      const i = todo[idx++];
      const file = join(out, i.set, `${i.name}.svg`);
      await mkdir(dirname(file), { recursive: true });
      const body = await get(`/i/${i.set}/${i.name}.svg`);
      await writeFile(file + ".tmp", body);
      await rename(file + ".tmp", file);
      n++;
    }
  }));
  let removed = 0;
  if (prune) for (const k of Object.keys(local)) if (!(k in next)) { await rm(join(out, `${k}.svg`), { force: true }); removed++; }
  if (flag("css")) {
    const rules = wanted.map((i) => `.zi-${i.name}{--zi:url("${i.set}/${i.name}.svg")}`).join("\n");
    const base = ".zi{display:inline-block;width:1em;height:1em;background-color:currentColor;-webkit-mask:var(--zi) center/contain no-repeat;mask:var(--zi) center/contain no-repeat;vertical-align:-.125em;flex:none}\n.zi-lg{width:1.33em;height:1.33em}.zi-xl{width:1.6em;height:1.6em}.zi-2x{width:2em;height:2em}.zi-3x{width:3em;height:3em}\n.zi-spin{animation:zi-spin 1s linear infinite}@keyframes zi-spin{to{transform:rotate(360deg)}}\n";
    await writeFile(join(out, "zi.css"), `/* generated by icons-sync from ${origin} */\n${base}${rules}\n`);
  }
  await writeFile(stateFile, JSON.stringify(next));
  say(`${origin}: ${wanted.length} icons, ${n} downloaded, ${removed} removed (version ${manifest.version})`);
}

const every = interval(opt("every", 0));
const run = () => once().catch((e) => { console.error(`sync failed: ${e.message}`); if (!every) process.exitCode = 1; });
await run();
if (every) { say(`refreshing every ${every / 60000} min`); setInterval(run, every); }
